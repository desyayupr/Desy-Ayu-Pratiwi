# Versi program yang menjalankan blok if
alien_color = 'green'

if alien_color == 'green':
    print("Selamat! Anda baru saja mendapatkan 5 poin karena menembak alien hijau.")
else:
    print("Selamat! Anda baru saja mendapatkan 10 poin.")
    
# Versi program yang menjalankan blok else
alien_color = 'yellow'

if alien_color == 'green':
    print("Selamat! Anda baru saja mendapatkan 5 poin karena menembak alien hijau.")
else:
    print("Selamat! Anda baru saja mendapatkan 10 poin.")

# struktur if-else: digunakan ketika ingin memberikan dua jalur alternatif keputusan. jika kondisi didalam 'if' bernilai 'true', blok pertama yang akan dijalankan.
# jika bernilai 'false', program otomatis akan beralih blok kode didalam 'else'
# 'if-else' jika pilihan kondisinya hanya 2 (ya/tidak, benar/salah)
# misal, alien hijau = 2 poin. yang bukan hijau akan mendapat 10 poin.