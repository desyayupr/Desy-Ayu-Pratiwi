# 1. Membuat dictionary untuk menyimpan informasi seseorang
person = {
    'first_name': 'Budi',
    'last_name': 'Santoso',
    'age': 22,
    'city': 'Surakarta'
}

# 2. Mencetak setiap informasi yang tersimpan di dalam dictionary
print(f"Nama Depan : {person['first_name']}")
print(f"Nama Belakang: {person['last_name']}")
print(f"Usia       : {person['age']} tahun")
print(f"Kota       : {person['city']}")

# pada contoh di atas, 'first_name', 'age', 'city' merupakan keys.
# sedangkan 'Budi', 'Santoso', 22, 'Surakarta' adalah nilai (values) di dalamnya.