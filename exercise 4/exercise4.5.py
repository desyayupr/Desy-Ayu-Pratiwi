# membuat list angka 1-1.000.000
angka = list(range(1, 1000001))

# menggunakan min() untuk memastikan daftar mulai dari 1
print("Nilai terkecil (min):", min(angka))

# menggunakan max() untuk memastikan daftar terakhir di 1.000.000
print("Nilai terbesar (max):", max(angka))

# menggunakan sum() untuk menjumlahkan seluruh angka dari 1-1.000.000
print("Jumlah total (sum):", sum(angka))