# Daftar buah favorit
buah = ['apel', 'pisang', 'ceri', 'kurma', 'anggur', 'mangga', 'jeruk']

# Mengambil tiga item pertama
print(" Tiga item pertama dalam list adalah:")
print(buah[:3]) # ini artinya diambil dari indeks 0 sampai 3

# Mengambil tiga item dari tengah list
print("\n Tiga item dari tengah list adalah:")
print(buah[2:5])

# Mengambil tiga item terakhir
print("\n Tiga item terakhir dalam list adalah:")
print(buah[-3:])

# noted
# Slicing ([start:stop]): Digunakan untuk mengambil sebagian elemen dari sebuah list tanpa mengubah list aslinya.
