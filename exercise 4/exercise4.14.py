# PEP 8 (Panduan Gaya Penulisan Kode Python)

# pada latihan ini memerintahkan untuk membaca (reading exercise)

# PEP 8 (Python Enhancement Proposal 8) adalah dokumen resmi yang berisi panduan dan standar bagaimana menulis kode Python yang bersih, mudah dibaca, rapi, dan konsisten.

# beberapa aturan dasar dalam PEP 8 :
# 1. Menggunakan 4 spasi untuk setiap indentasi (bukan tab yang tidak konsisten)
# 2. Membatasi panjang maksimal setiap baris kode hingga 79 atau 80 karakter agar mudah dibaca di berbagai ukuran layar.
# 3. Menghindari penggunaan baris kosong (blank lines) secara berlebihan.
# 4. Menggunakan penamaan variabel yang deskriptif dengan huruf kecil dan garis bawah (misal: nama_variabel).

# noted:
# indentasi yaitu jarak atau spasi kosong diawal baris kode