# menggunakan for loop dan range (1, 21) untuk mencetak angka 1-20
for angka in range(1, 21):
    print(angka)
    
# noted:
# maksud dari range (1, 21): fungsi range() menghasilkan deretan angka dari angka pertama (1) sampai sebelum angka kedua (21). oleh karena itu, agar angka 20 ikut tercetak, maka harus manulis batas akhirnya hingga 21
